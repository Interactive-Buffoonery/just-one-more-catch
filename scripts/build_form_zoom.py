"""Generate form tile zoom from local sprites only. Run with uv run --with pillow."""
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent


def zoom_factor(canvas, extent):
    return min(250, canvas * 100 // extent)


def build():
    result = {}
    for source in sorted((ROOT / 'client/data').glob('*.ts')):
        text = source.read_text()
        if not text.startswith('// Generated by scripts/build_data.py'):
            continue
        pack = source.stem
        species = {}
        # Group the pack's form sprites by the species prefix in their ids.
        groups = {}
        for path in sorted((ROOT / 'public/sprites' / pack / 'forms').glob('*.png')):
            prefix = path.stem.split('-')[0]
            with Image.open(path) as image:
                box = image.convert('RGBA').getchannel('A').getbbox()
                extent = max(box[2] - box[0], box[3] - box[1])
                groups.setdefault(prefix, []).append((image.width, extent))
        for prefix, sizes in groups.items():
            species[prefix] = zoom_factor(sizes[0][0], max(e for _, e in sizes))
        result[pack] = species
    (ROOT / 'client/data/form-zoom.ts').write_text('// Generated by scripts/build_form_zoom.py. Do not edit.\nexport default ' + json.dumps(result, separators=(',', ':')) + ' as Record<string, Record<string, number>>;\n')


if __name__ == '__main__':
    build()
