"""Regression checks for combined regional sections and X/Y source rows."""
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sys.argv = [str(root / 'scripts/build_data.py'), 'xy']
spec = importlib.util.spec_from_file_location('build_data', root / 'scripts/build_data.py')
build = importlib.util.module_from_spec(spec)
spec.loader.exec_module(build)
combined = build.regional_dex([12, 13, 14])
assert len(combined) == 457
assert sorted(combined.values()) == list(range(1, 458))
assert combined[650] == 1
assert combined[718] > 306
for dex in (12, 13, 14):
    entries = build.cached(f'pokedex_{dex}')['pokemon_entries']
    assert build.regional_dex(dex) == {
        int(e['pokemon_species']['url'].rstrip('/').split('/')[-1]): e['entry_number']
        for e in entries
    }
# Rebuilding every pre-existing pack must leave its generated bytes unchanged.
for path in sorted((root / 'data').glob('*.json')):
    if path.stem == 'xy':
        continue
    output = root / 'client/data' / (path.stem + '.ts')
    before = output.read_bytes()
    try:
        subprocess.run([sys.executable, str(root / 'scripts/build_data.py'), path.stem], check=True, cwd=root)
        assert output.read_bytes() == before, f'{path.stem} changed'
    finally:
        if output.read_bytes() != before:
            output.write_bytes(before)

game = json.loads((root / 'client/data/xy.ts').read_text().split('export default ')[1].strip().removesuffix(';'))
def rows(n):
    return game['dex'][n - 1]['rows']
assert {r['v'] for r in rows(716)} == {'X'}
assert {r['v'] for r in rows(717)} == {'Y'}
assert all('Roaming' not in r['place'] for n in (144, 145, 146) for r in rows(n))
assert all('bird-sightings' in r['need'] and 'Elite Four' in r['need'] for n in (144, 145, 146) for r in rows(n))
assert any(r['m'] == 'horde' for p in game['dex'] for r in p['rows'])
assert rows(143)[0]['need'] == ['poke-flute-recovered']
assert any('mega-ring-demonstration' in r['need'] for r in rows(448) if r['m'] == 'gift')
assert all(r['place'] == 'Ambrette Town' for n in (696, 698) for r in rows(n) if r['m'] == 'gift')
assert sum(bool(p['j']) for p in game['dex']) == 457
print('X/Y: combined dex, exclusions, special gates and unchanged existing packs ok')
