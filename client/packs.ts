// Everything that differs between games. Encounter data is generated per pack
// and loaded only when a playthrough of that game is opened.
import type { VersionId } from "../shared/versions";

export type GameData = {
  chapters: {
    title: string;
    needs: string[];
    kit?: string;
    places: string[];
  }[];
  dex: any[];
};
export type Pack = {
  load: () => Promise<GameData>;
  region: string;
  regional: number;
  national: number;
  start: string;
  starters: number[];
  badges: string[][];
  postgame?: [string, string[][]];
  kit: string[][];
  safari?: string[];
  nightFrom?: number;
  boxes: [count: number, size: number];
};
export type Version = {
  name: string;
  short: string;
  code: string;
  gen: string;
  pack: Pack;
  other?: string;
  ring: string[];
};

